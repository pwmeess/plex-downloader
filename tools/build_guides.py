#!/usr/bin/env python3
"""Builds the EN/PL guides from docs/guide.<lang>.md (run by the developer, not on the Pi):

    pip install markdown playwright   # once
    python3 tools/build_guides.py

Output (committed, so the Pi needs nothing extra):
    static/guide/guide.<lang>.html                  – fragment shown in the app at /guide
    static/guide/plex-downloader-guide-<lang>.pdf   – PDF to download
"""
import html
import os
import re
import sys

import markdown

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "static", "guide")
LANGS = {"en": ("Contents", "Download PDF", "Plex Downloader – guide"),
         "pl": ("Spis treści", "Pobierz PDF", "Plex Downloader – instrukcja")}

PRINT_CSS = """
@page { size: A4; margin: 18mm 16mm 18mm 16mm; }
body { font-family: "Inter", "Helvetica Neue", Arial, sans-serif; font-size: 10.5pt; line-height: 1.5; color: #1d232c; }
h1 { font-size: 22pt; margin: 0 0 6pt; color: #b77d00; }
h2 { font-size: 15pt; margin: 22pt 0 6pt; padding-top: 6pt; border-top: 1.5pt solid #e5a00d; page-break-after: avoid; }
h3 { font-size: 12pt; margin: 14pt 0 4pt; page-break-after: avoid; }
code { font-family: "JetBrains Mono", Menlo, Consolas, monospace; font-size: 9pt; background: #f2f4f7; padding: 0 2pt; border-radius: 2pt; }
pre { background: #f2f4f7; border: 0.5pt solid #d7dce3; border-radius: 4pt; padding: 7pt 9pt; white-space: pre-wrap; word-break: break-word; page-break-inside: avoid; }
pre code { background: none; padding: 0; }
table { border-collapse: collapse; width: 100%; margin: 6pt 0; page-break-inside: avoid; }
th, td { border: 0.5pt solid #c9d0da; padding: 4pt 6pt; text-align: left; vertical-align: top; }
th { background: #f2f4f7; }
blockquote { margin: 8pt 0; padding: 4pt 10pt; border-left: 3pt solid #e5a00d; background: #fff8e8; }
a { color: #8a5d00; text-decoration: none; }
.toc { border: 0.5pt solid #d7dce3; border-radius: 4pt; padding: 6pt 12pt; margin: 10pt 0 4pt; }
.toc ol { margin: 4pt 0; padding-left: 16pt; }
.meta { color: #6b7380; font-size: 9pt; }
"""


def _prepare(src):
    """Python-Markdown needs 4-space indents in lists and has no fenced code inside list items:
    3-space indents become 4, and an indented ``` block becomes an indented code block."""
    out, fence = [], None
    for line in src.split("\n"):
        m = re.match(r"^( +)```", line)
        if fence is None and m:
            fence = len(m.group(1))
            out.append("")
            continue
        if fence is not None:
            if line.strip() == "```":
                fence = None
                out.append("")
            else:
                out.append("        " + line[fence:])
            continue
        if re.match(r"^ {3}\S", line):
            line = " " + line
        # a new list item right after indented text would be glued to that paragraph
        if re.match(r"^(\d+\.|-) ", line) and out and out[-1].startswith(" ") and out[-1].strip():
            out.append("")
        out.append(line)
    return "\n".join(out)


def convert(lang):
    src = _prepare(open(os.path.join(ROOT, "docs", "guide.%s.md" % lang), encoding="utf-8").read())
    body = markdown.markdown(src, extensions=["tables", "fenced_code", "attr_list", "sane_lists"])
    toc = re.findall(r'<h2 id="([^"]+)">(.*?)</h2>', body)
    return body, toc


def main():
    version = open(os.path.join(ROOT, "VERSION")).read().strip()
    os.makedirs(OUT, exist_ok=True)
    pdfs = []
    for lang, (contents, _dl, title) in LANGS.items():
        body, toc = convert(lang)
        nav = "<nav class=\"guide-toc\"><b>%s</b><ol>%s</ol></nav>" % (
            contents, "".join('<li><a href="#%s">%s</a></li>' % (i, re.sub(r"^\d+\.\s*", "", t)) for i, t in toc))
        with open(os.path.join(OUT, "guide.%s.html" % lang), "w", encoding="utf-8") as f:
            f.write("<!-- generated by tools/build_guides.py from docs/guide.%s.md – do not edit -->\n" % lang)
            f.write(nav + "\n<article class=\"guide-body\">\n" + body + "\n</article>\n")
        doc = ("<!doctype html><html lang=\"%s\"><head><meta charset=\"utf-8\"><title>%s</title><style>%s</style></head>"
               "<body><p class=\"meta\">Plex Downloader %s · github.com/pwmeess/plex-downloader</p>%s%s</body></html>") % (
            lang, html.escape(title), PRINT_CSS, version,
            "<div class=\"toc\"><b>%s</b><ol>%s</ol></div>" % (contents, "".join(
                '<li><a href="#%s">%s</a></li>' % (i, re.sub(r"^\d+\.\s*", "", t)) for i, t in toc)), body)
        pdfs.append((lang, doc))
    from playwright.sync_api import sync_playwright
    with sync_playwright() as p:
        kw = {"executable_path": "/usr/bin/google-chrome"} if os.path.exists("/usr/bin/google-chrome") else {}
        br = p.chromium.launch(**kw)
        page = br.new_page()
        for lang, doc in pdfs:
            page.set_content(doc, wait_until="load")
            out = os.path.join(OUT, "plex-downloader-guide-%s.pdf" % lang)
            page.pdf(path=out, format="A4", print_background=True, display_header_footer=True,
                     header_template="<span></span>",
                     footer_template='<div style="font-size:8px;color:#888;width:100%;text-align:center;">'
                                     '<span class="pageNumber"></span> / <span class="totalPages"></span></div>',
                     margin={"top": "16mm", "bottom": "16mm", "left": "14mm", "right": "14mm"})
            print("ok", out, os.path.getsize(out))
        br.close()


if __name__ == "__main__":
    sys.exit(main())
